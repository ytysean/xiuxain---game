def _build_base_poses():
    """合并 UPPER + 肢节，生成 BASE_POSES（保证 halfbody 与 stand 上身锚点一致）。"""
    poses = {}
    for pers in UPPER:                       # 6 性格完整底座
        poses[(pers, "stand")] = ({**UPPER[pers], **LIMBS_STAND[pers]}, False)
        poses[(pers, "halfbody")] = ({**UPPER[pers], **LIMBS_HALFBODY[pers]}, True)
        if pers in BATTLE:
            poses[(pers, "battle")] = (BATTLE[pers], False)
    return poses


