W, H = 1024, 1536

# OpenPose COCO 18 关键点索引
# 0鼻 1颈 2右肩 3右肘 4右腕 5左肩 6左肘 7左腕 8右髋 9右膝 10右踝 11左髋 12左膝 13左踝 14右眼 15左眼 16右耳 17左耳
# 肢体连接对（前 6 对=肩臂，后 9 对=躯干+腿）；半身姿只取前 6 对
POSE_PAIRS = [
    (1, 2), (1, 5), (2, 3), (3, 4), (5, 6), (6, 7),        # 肩 + 双臂
    (1, 8), (8, 9), (9, 10), (1, 11), (11, 12), (12, 13),  # 躯干 + 双腿
    (2, 8), (5, 11), (8, 11),                              # 侧身躯干 + 髋线
]
PALETTE = [
    [255, 0, 0], [255, 85, 0], [255, 170, 0], [255, 255, 0], [170, 255, 0], [85, 255, 0],
    [0, 255, 0], [0, 255, 85], [0, 255, 170], [0, 255, 255], [0, 170, 255], [0, 85, 255],
    [0, 0, 255], [85, 0, 255], [170, 0, 255],
]


def _head(kp, r=170):
    """头中心与半径（与构图锁一致：头高约占图高 22%，头顶留白约 10%）。"""
    if 0 in kp and 14 in kp and 15 in kp:
        cx = kp[0][0]
        cy = (kp[14][1] + kp[0][1]) // 2
        return (cx, cy), r
    return None, 0


def draw_pose(kp, halfbody, out_path, head_r=170, head_y=0, lw=16):
    img = Image.new("RGB", (W, H), (0, 0, 0))
    d = ImageDraw.Draw(img)
    pairs = POSE_PAIRS[:6] if halfbody else POSE_PAIRS
    # 头部位移副本（头身比/头顶位置按性别微调）
    kp_h = dict(kp)
    for i in (0, 14, 15, 16, 17):
        if i in kp_h:
            x, y = kp_h[i]
            kp_h[i] = (x, y + head_y)
    for (a, b), col in zip(pairs, PALETTE):
        if a in kp and b in kp:
            d.line([kp[a], kp[b]], fill=tuple(col), width=lw)
    # 关节点
    for idx, pt in kp.items():
        if idx in (8, 9, 10, 11, 12, 13) and halfbody:
            continue
        d.ellipse([pt[0] - 13, pt[1] - 13, pt[0] + 13, pt[1] + 13], fill=(255, 255, 255))
    # 头部：外圈 + 五官点（用位移副本）
    center, r = _head(kp_h, head_r)
    if center:
        d.ellipse([center[0] - r, center[1] - r, center[0] + r, center[1] + r],
                  outline=(255, 0, 255), width=10)
        for f in (0, 14, 15, 16, 17):
            if f in kp_h:
                d.ellipse([kp_h[f][0] - 14, kp_h[f][1] - 14, kp_h[f][0] + 14, kp_h[f][1] + 14],
                          fill=(255, 255, 255))
        for (a, b) in ((14, 0), (15, 0), (14, 16), (15, 17)):
            if a in kp_h and b in kp_h:
                d.line([kp_h[a], kp_h[b]], fill=(255, 255, 255), width=4)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    img.save(out_path)
    return out_path


