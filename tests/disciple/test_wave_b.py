# ============ 1. 弟子ID 唯一分配 + 载入重置 ============
def test_弟子ID分配():
    print("== 弟子ID 分配器 ==")
    # 新建 6 名弟子：计数器 1→6，ID 各自唯一
    计数器 = 1
    ids = []
    for _ in range(6):
        i, 计数器 = M.分配ID(计数器)
        ids.append(i)
    check("新建 6 名 ID 唯一", len(set(ids)) == 6 and ids == [1, 2, 3, 4, 5, 6])

    # 载入旧档（ID 乱序/非连续）：重置后计数器 = max+1，新建不冲突
    载入IDs = [3, 1, 5, 7, 2]
    计数器 = M.载入后重置ID(载入IDs)
    check("载入重置计数器=max+1=8", 计数器 == 8, "实际 %d" % 计数器)
    新IDs = []
    for _ in range(3):
        i, 计数器 = M.分配ID(计数器)
        新IDs.append(i)
    合并 = set(载入IDs) | set(新IDs)
    check("新建 ID 与旧档不重", len(合并) == len(载入IDs) + len(新IDs), "合并=%s" % sorted(合并))
    check("新建 ID 连续=8,9,10", 新IDs == [8, 9, 10])

    # 空档回退 1
    check("空载入→重置为1", M.载入后重置ID([]) == 1)


# ============ 2. 取弟子纪事：ID 过滤 + 姓名回退 ============
def test_取弟子纪事():
    print("== 取弟子纪事 ==")
    纪事 = [
        {"日": 1, "弟子": "张三", "弟子ID": 5, "名称": "突破"},
        {"日": 2, "弟子": "张三", "弟子ID": 5, "名称": "晋升"},   # 同 ID 第二条
        {"日": 3, "弟子": "李四", "弟子ID": 0, "名称": "旧档坐化"},  # 旧档缺 ID，靠姓名
        {"日": 4, "弟子": "王五", "弟子ID": 9, "名称": "奇遇"},
    ]
    r5 = M.取弟子纪事(纪事, 5, "张三")
    check("按ID=5 取回张三全部(2条)", len(r5) == 2 and all(e["弟子ID"] == 5 for e in r5))
    # 旧档缺 ID：仅靠姓名回退
    r李 = M.取弟子纪事(纪事, 0, "李四")
    check("旧档缺ID按姓名=李四 取回1条", len(r李) == 1 and r李[0]["弟子"] == "李四")
    # 姓名回退不误抓同名不同 ID 的新 entry（此处无重名，验证空集）
    r空 = M.取弟子纪事(纪事, 99, "王五")
    check("不存在的ID+姓名→空", len(r空) == 0)
    # 旧档缺ID且姓名不匹配→空（防旧档混显风险）
    r误 = M.取弟子纪事(纪事, 0, "赵六")
    check("缺ID且姓名不符→空", len(r误) == 0)


# ============ 3. 品级权益：门派等级 → 品级映射 ============
def test_品级映射():
    print("== 品级权益映射 ==")
    表 = M.品级权益表()
    check("CSV 解析得 4 行", len(表) == 4, "实际 %d" % len(表))
    check("列含 品级/门派等级阈值/编制上限/解锁功能/弹窗标题/弹窗文案",
          all(all(k in r for k in ["品级", "门派等级阈值", "编制上限", "解锁功能", "弹窗标题", "弹窗文案"]) for r in 表))
    # 阈值 1/3/5/7 对应 九/八/七/六
    期望 = [(1, "九品"), (3, "八品"), (5, "七品"), (7, "六品")]
    for lv, 品 in 期望:
        r = M.门派等级到品级权益(lv)
        check("门派Lv%d→%s" % (lv, 品), r.get("品级") == 品, "实际 %s" % r.get("品级"))
    # 中间档取最高可达档
    check("Lv2→九品(阈值1)", M.门派等级到品级权益(2).get("品级") == "九品")
    check("Lv4→八品(阈值3)", M.门派等级到品级权益(4).get("品级") == "八品")
    check("Lv6→七品(阈值5)", M.门派等级到品级权益(6).get("品级") == "七品")
    check("Lv10→六品(阈值7,封顶)", M.门派等级到品级权益(10).get("品级") == "六品")
    # 展示字段非空
    r = M.门派等级到品级权益(7)
    check("弹窗标题非空", r.get("弹窗标题", "") != "")
    check("弹窗文案非空", r.get("弹窗文案", "") != "")


