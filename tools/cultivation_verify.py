#!/usr/bin/env python3
# 修炼周期治理 数值验算（P0+P1 边界断言）
# 复刻 disciple.gd 新公式，做确定性最快路径仿真（突破必成功 → 取最短时间，用于验证年龄地板）。
# 不依赖 Godot，纯 python 回归；由 pre_f5 外的数值守卫调用。

灵根品阶速度 = {"凡品": 1.0, "良品": 1.3, "上品": 1.8, "极品": 2.5, "天品": 2.5}
每层所需日_新 = {"练气": 108.0, "筑基": 288.0, "金丹": 720.0, "元婴": 1800.0, "化神": 3600.0, "仙阶": 7200.0}
资质突破系数 = {"fan_su": 0.60, "pingyong": 0.75, "youliang": 1.00, "tiancai": 1.00, "yaonie": 1.10, "kuangshi": 1.20}
最低突破年龄 = {"筑基": 14.0, "金丹": 22.0, "元婴": 50.0}
宗门加成封顶 = 1.0  # +100% → ×2


def 宗门乘区(灵脉等级=10, 气运=0.03, 负责人=0.06, 藏经阁=0.05):
    pct = min(灵脉等级, 10) * 0.02 + 气运 + 负责人 + 藏经阁
    pct = max(0.0, min(pct, 宗门加成封顶))
    return 1.0 + pct


def 仿真到金丹(灵根档, 资质, 宗门倍率=1.0, 初始年龄=12.0):
    """确定性最快路径：突破必成功。返回 (筑基大圆满年龄, 金丹突破年龄)。"""
    速度 = 灵根品阶速度[灵根档] * 宗门倍率
    天数 = 0.0
    for 境 in ("练气", "筑基"):
        每层 = 每层所需日_新[境] / 速度
        天数 += 每层 * 10
    筑基大圆满年龄 = 初始年龄 + 天数 / 360.0
    # D方案：金丹突破需 瓶颈打磨满(=年龄/22≥1) 且 年龄≥22 → 最快 = max(筑基大圆满年龄, 22)
    金丹年龄 = max(筑基大圆满年龄, 最低突破年龄["金丹"])
    return 筑基大圆满年龄, 金丹年龄


def main():
    fails = []
    # 1) 宗门加成封顶：满配不超过 ×2
    assert 宗门乘区() <= 2.0 + 1e-9, "宗门加成超 ×2"
    # 2) 金丹最快年龄地板 ≥ 22（所有组合）
    组合 = [
        ("凡品", "fan_su"), ("凡品", "kuangshi"),
        ("良品", "youliang"), ("上品", "tiancai"),
        ("极品", "fan_su"), ("天品", "kuangshi"),
    ]
    for 灵根档, 资质 in 组合:
        for 宗门倍率 in (1.0, 2.0):
            筑基年龄, 金丹年龄 = 仿真到金丹(灵根档, 资质, 宗门倍率)
            if 金丹年龄 < 22.0 - 1e-9:
                fails.append(f"金丹年龄<22: {灵根档}/{资质}/宗门{宗门倍率} → {金丹年龄:.2f}")
            # 3) 天才应远快于普通（筑基大圆满年龄随灵根/宗门下降）
    # 4) 关键基准校验（对齐设计文档验算表）
    天灵满配 = 仿真到金丹("天品", "kuangshi", 2.0)
    下品无加成 = 仿真到金丹("凡品", "fan_su", 1.0)
    assert abs(天灵满配[0] - 14.2) < 0.5, f"天灵根满配筑基大圆满年龄异常: {天灵满配[0]}"
    assert 下品无加成[1] >= 22.0, f"下品无加成金丹年龄异常: {下品无加成[1]}"
    # 5) 资质突破系数边界（凡俗0.6 / 旷世1.2）
    assert 资质突破系数["fan_su"] == 0.60 and 资质突破系数["kuangshi"] == 1.20

    if fails:
        print("FAIL:")
        for f in fails:
            print("  -", f)
        raise SystemExit(1)
    print("OK: 修炼周期验算全部通过")
    print(f"  天灵根满配: 筑基大圆满年龄={天灵满配[0]:.1f}, 金丹突破年龄={天灵满配[1]:.1f}")
    print(f"  下品无加成: 筑基大圆满年龄={下品无加成[0]:.1f}, 金丹突破年龄={下品无加成[1]:.1f}")


if __name__ == "__main__":
    main()
