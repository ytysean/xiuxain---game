import sys
sys.path.insert(0, __file__.rsplit("/", 1)[0])
import disciple_math as M

PASS = 0
FAIL = 0


def check(名: str, 条件: bool, 附: str = ""):
    global PASS, FAIL
    if 条件:
        PASS += 1
        print("  ✅ %s" % 名)
    else:
        FAIL += 1
        print("  ❌ %s  %s" % (名, 附))


# ============ 1. 资质→境界天花板映射（6 档资质对齐代码实际）============
def test_天花板映射():
    print("== 资质→境界天花板映射 ==")
    check("凡俗→金丹", M.资质上限境界("fan_su") == "金丹")
    check("平庸→元婴", M.资质上限境界("pingyong") == "元婴")
    check("优良→化神", M.资质上限境界("youliang") == "化神")
    check("天才→仙阶", M.资质上限境界("tiancai") == "仙阶")
    check("妖孽→道阶", M.资质上限境界("yaonie") == "道阶")
    check("旷世→道阶", M.资质上限境界("kuangshi") == "道阶")


# ============ 2. 达资质上限判定 ============
def test_达上限判定():
    print("== 是否达资质上限 ==")
    # 凡俗在金丹（天花板）即封顶；在筑基未到顶
    check("凡俗@金丹=达上限", M.是否达资质上限("金丹", "fan_su"))
    check("凡俗@筑基=未达上限", not M.是否达资质上限("筑基", "fan_su"))
    check("凡俗@元婴=达上限(已超)", M.是否达资质上限("元婴", "fan_su"))
    # 妖孽在道阶（天花板）封顶；在仙阶未到顶
    check("妖孽@道阶=达上限", M.是否达资质上限("道阶", "yaonie"))
    check("妖孽@仙阶=未达上限", not M.是否达资质上限("仙阶", "yaonie"))


# ============ 3. 突破天花板拦截（核心铁律：到顶不可再突破，不惩罚）============
def test_突破拦截():
    print("== 尝试突破天花板拦截 ==")
    # 凡俗在金丹（天花板）——目标境元婴超出上限，应被拦截
    check("凡俗@金丹 不可突破→元婴", not M.尝试突破_allowed("金丹", "fan_su"))
    # 凡俗在筑基——目标境金丹=天花板本身，允许抵达（金丹是可达上限）
    check("凡俗@筑基 可突破→金丹", M.尝试突破_allowed("筑基", "fan_su"))
    # 妖孽在仙阶——目标境道阶=天花板，允许抵达
    check("妖孽@仙阶 可突破→道阶", M.尝试突破_allowed("仙阶", "yaonie"))
    # 妖孽在道阶（顶阶）——无可突破
    check("妖孽@道阶 无可突破", not M.尝试突破_allowed("道阶", "yaonie"))
    # 平庸在金丹——目标境元婴=天花板，允许抵达
    check("平庸@金丹 可突破→元婴", M.尝试突破_allowed("金丹", "pingyong"))


# ============ 4. 坐化触发条件（年龄 >= 当前境界寿元）============
def test_坐化触发():
    print("== 寿元坐化触发 ==")
    check("年龄=寿元→坐化", M.是否坐化(500.0, 500))
    check("年龄>寿元→坐化", M.是否坐化(501.0, 500))
    check("年龄<寿元→未坐化", not M.是否坐化(499.0, 500))
    check("练气80岁满→坐化", M.是否坐化(80.0, M.境界寿元["练气"]))
    check("金丹500岁满→坐化", M.是否坐化(500.0, M.境界寿元["金丹"]))


# ============ 5. 坐化资产回收统计（灵兽+物品归还宗门）============
def test_坐化回收():
    print("== 坐化资产回收 ==")
    # 双宠 + 2装备 + 3背包
    弟子 = {"主宠灵兽": object(), "副宠灵兽": object(),
            "装备": {"法兵": 1, "道冠": 1}, "背包": [1, 2, 3]}
    r = M.坐化回收(弟子)
    check("双宠回收=2", r["灵兽回收"] == 2)
    check("物品回收=5", r["物品回收"] == 5)
    # 无宠 + 空背包
    弟子2 = {"主宠灵兽": None, "副宠灵兽": None, "装备": {}, "背包": []}
    r2 = M.坐化回收(弟子2)
    check("无宠回收=0", r2["灵兽回收"] == 0)
    check("空物品回收=0", r2["物品回收"] == 0)


