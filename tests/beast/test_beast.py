# ============ 6. 随行灵兽徽标格式（S1-3 UI 契约：主·名 / 副·名，孵化中不列） ============
def test_灵兽随行徽标():
    print("== 随行灵兽徽标格式（主·名 / 副·名）==")
    def 徽(主名, 主孵, 副名, 副孵):
        段 = ""
        if 主名 and not 主孵:
            段 += "主·" + 主名
        if 副名 and not 副孵:
            段 += ("  " if 段 else "") + "副·" + 副名
        return 段
    check("仅主宠=主·朱雀", 徽("朱雀", False, "", False) == "主·朱雀")
    check("主+副=主·朱雀  副·灵尾兔", 徽("朱雀", False, "灵尾兔", False) == "主·朱雀  副·灵尾兔")
    check("主宠孵化中不列(仅副)", 徽("朱雀", True, "灵尾兔", False) == "副·灵尾兔")
    check("双孵化=空", 徽("朱雀", True, "灵尾兔", True) == "")


# ============ 7. T13 等级养成：本体战力 ×(1+单级×等级差)，单级=0.3/(上限-1)，满级锁死+30% ============
def test_等级():
    print("== T13 等级养成：本体战力等级因子（满级锁死+30%）==")
    # 1级 = 旧基准（不加成）
    check("凡阶 attack 1级=66", M.本体战力("fan_jie", "attack", False, 1) == 66)
    check("道阶 attack 1级=3234", M.本体战力("dao_jie", "attack", False, 1) == 3234)
