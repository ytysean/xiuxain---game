# ============ 2. 双层适配加成：职业类型 +20% / 灵根属性 +8% / T14忠诚 +8% / 上限 36% ============
def test_calc_beast_bonus():
    print("== 双层适配加成：职业 +20% / 灵根 +8% / 忠诚 +8% / 上限 36% ==")
    # 以下用例忠诚=0（仅测职业/灵根双层，忠诚0不惩罚）
    # attack + 道修职业 + 灵根匹配火 → 0.28（双满）
    check("attack+道修+灵根火=0.28",
          abs(M.calc_beast_bonus("attack", "灵根", "火", "道修", "火", 0) - 0.28) < 1e-9,
          "got %s" % M.calc_beast_bonus("attack", "灵根", "火", "道修", "火", 0))
    # defense + 体修职业（无灵根匹配）→ 0.20
    check("defense+体修=0.20",
          abs(M.calc_beast_bonus("defense", "职业", "道修", "体修", "金", 0) - 0.20) < 1e-9,
          "got %s" % M.calc_beast_bonus("defense", "职业", "道修", "体修", "金", 0))
    # support + 御兽师 → 0.20
    check("support+御兽师=0.20",
          abs(M.calc_beast_bonus("support", "", "", "御兽师", "木", 0) - 0.20) < 1e-9)
    # attack + 体修（类型不匹配）+ 无灵根匹配 → 0.0
    check("attack+体修无契合=0.0",
          abs(M.calc_beast_bonus("attack", "职业", "道修", "体修", "火", 0) - 0.0) < 1e-9)
    # 灵根天赋匹配但职业为空 → 仅 +0.08（职业层跳过，灵根层仍生效）
    check("职业空+灵根火=0.08",
          abs(M.calc_beast_bonus("attack", "灵根", "火", "", "火", 0) - 0.08) < 1e-9)
    # 灵根天赋不匹配 → 0.0（即使职业匹配，灵根不叠加错配）
    check("attack+道修+灵根错配=0.20",
          abs(M.calc_beast_bonus("attack", "灵根", "水", "道修", "火", 0) - 0.20) < 1e-9)


# ============ 3. 灵兽契约战力：主宠100%×0.30 / 副宠30%×0.30 / 待命0 / 孵化跳过 ============
def test_灵兽契约战力():
    print("== 灵兽契约战力：主宠/副宠/待命/孵化中 ==")
    # 主宠：凡阶 attack，道修(bonus0.20，不带灵根天赋) → 本体66×(1.2)=79 → ×0.30×1.0 = int(23.7)=23
    主 = 造宠("fan_jie", "attack", is_main=True)
    check("主宠单只贡献=23",
          灵兽契约战力_直算([主], "道修", "火") == 23,
          "got %d" % 灵兽契约战力_直算([主], "道修", "火"))
    # 副宠：同上 → 79 → ×0.30×0.3 = int(7.11)=7
    副 = 造宠("fan_jie", "attack", is_deputy=True)
    check("副宠单只贡献=7",
          灵兽契约战力_直算([副], "道修", "火") == 7,
          "got %d" % 灵兽契约战力_直算([副], "道修", "火"))
    # 待命（既非主也非副）→ 0
    待 = 造宠("fan_jie", "attack", is_main=False, is_deputy=False)
    check("待命贡献=0", 灵兽契约战力_直算([待], "道修", "火") == 0)
    # 孵化中 → 跳过（0）
    蛋 = 造宠("fan_jie", "attack", 孵化中=True, is_main=True)
    check("孵化中贡献=0", 灵兽契约战力_直算([蛋], "道修", "火") == 0)
    # 主+副 同弟子叠加：23 + 7 = 30
    check("主宠+副宠叠加=30",
          灵兽契约战力_直算([主, 副], "道修", "火") == 30,
          "got %d" % 灵兽契约战力_直算([主, 副], "道修", "火"))
    # 无契合弟子（职业不匹配、灵根不匹配）→ 主宠仅 +0%：66×1.0=66 → ×0.30 = int(19.8)=19
    主裸 = 造宠("fan_jie", "attack", is_main=True)
    check("无契合主宠贡献=19",
          灵兽契约战力_直算([主裸], "体修", "水") == 19,
          "got %d" % 灵兽契约战力_直算([主裸], "体修", "水"))


