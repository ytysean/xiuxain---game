    args = ap.parse_args()

    genders = [args.gender] if args.gender else list(GENDER_PARAMS.keys())
    n = 0
    for (pers, ptype), (base, hb) in BASE_POSES.items():
        if args.pers and pers != args.pers:
            continue
        for gender in genders:
            p = GENDER_PARAMS[gender]
            kp, eff = build_kp(base, gender, ptype)
            fname = f"pose_{pers}_{gender}_{ptype}.png"
            out = os.path.join(args.out, fname)
            draw_pose(kp, hb, out, head_r=eff["head_r"], head_y=eff["head_y"], lw=eff["lw"])
