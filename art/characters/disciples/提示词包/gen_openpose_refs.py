# 性别量化参数（与 master 规范「男女体态差异判断标准」表一一对应）
#   肩宽 shoulder：正值=加宽（男性倒三角），负值=收窄（女性）
#   胯宽 hip：正值=加宽（女性梨形），负值=收窄（男性）
#   腰节高度 hip_y：正值=髋线下移（男性腰低），负值=上移（女性腰高）
#   头身比：head_r 头半径（男小女大）；head_y 头顶纵向偏移；limb 四肢长度系数；lw 线宽
# ---------------------------------------------------------------------------
GENDER_PARAMS = {
    "男": dict(shoulder=30, hip=-22, hip_y=14, head_r=158, head_y=8, limb=1.045, lw=20),
    "女": dict(shoulder=-24, hip=22, hip_y=-12, head_r=192, head_y=-6, limb=0.955, lw=13),
}

# 战斗姿女性力量保留系数：收窄/外扩幅度回调，避免女战姿被画弱
BATTLE_FEMALE = {"shoulder": 0.45, "hip": 0.5}   # shoulder -24→-11, hip +22→+11


def build_kp(base, gender, ptype="stand"):
    """在底模关节上叠加性别量化差异，返回新关节字典。"""
    p = dict(GENDER_PARAMS[gender])
    if ptype == "battle" and gender == "女":
        # 近战女弟子战斗姿保留起手张力：收窄回调、梨形收敛
        p["shoulder"] = int(round(p["shoulder"] * BATTLE_FEMALE["shoulder"]))
        p["hip"] = int(round(p["hip"] * BATTLE_FEMALE["hip"]))
    kp = {k: (x, y) for k, (x, y) in base.items()}
    # ① 肩宽：2=画面左肩，5=画面右肩
    if 2 in kp:
        kp[2] = (kp[2][0] - p["shoulder"], kp[2][1])
    if 5 in kp:
        kp[5] = (kp[5][0] + p["shoulder"], kp[5][1])
    # ② 胯宽 + ③ 腰节高度：8=画面左髋，11=画面右髋
    if 8 in kp:
        kp[8] = (kp[8][0] + p["hip"], kp[8][1] + p["hip_y"])
    if 11 in kp:
        kp[11] = (kp[11][0] - p["hip"], kp[11][1] + p["hip_y"])
    # ④ 四肢长度（从根关节等比缩放，保持姿态方向不变）
    roots = {2: 2, 3: 2, 4: 2, 5: 5, 6: 5, 7: 5, 8: 8, 9: 8, 10: 8, 11: 11, 12: 11, 13: 11}
    for j, r in roots.items():
        if j in kp and j != r:
            rx, ry = kp[r]
            ox, oy = kp[j]
            kp[j] = (round(rx + (ox - rx) * p["limb"]), round(ry + (oy - ry) * p["limb"]))
    return kp, p


