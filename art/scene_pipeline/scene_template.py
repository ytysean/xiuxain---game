# ---------------------------------------------------------------------------
# 提示词组装
# ---------------------------------------------------------------------------
def build_negative():
    """把负面池折叠为正向“禁止：…”串（ImageGen 无原生 negative_prompt）。"""
    return "禁止：" + "、".join(BASE_CONFIG["negative_pool_cn"])


def assemble_prompt(scene_id, season, with_negative=True):
    """组装单条完整 prompt（中文，ImageGen 直接消费）。

    结构：基底风格 + 天光 + 植被 + 环境特效 + 额外 + 美术约束 + 品质 + 负面折叠
    """
    scene = SCENES[scene_id]
    sv = SEASONS[season]
    parts = [scene["base_arch"], sv["sky"], sv["plant"], sv["effect"]]
    if sv.get("extra"):
        parts.append(sv["extra"])
    if sv.get("constraints"):
        parts.append("；".join(sv["constraints"]))
    if BASE_CONFIG.get("positive_enhance_cn"):
        parts.append("".join(BASE_CONFIG["positive_enhance_cn"]))
    parts.append(BASE_CONFIG["quality_cn"])
    prompt = "，".join(p for p in parts if p)
    if with_negative:
        prompt = prompt + "，" + build_negative()
    return prompt


def assemble_payload(scene_id, season):
    """返回结构化 payload（供 batch_gen 写队列 / 前端展示）。"""
    sv = SEASONS[season]
    return {
        "scene_id": scene_id,
        "scene_name": SCENES[scene_id]["name"],
        "season": season,
        "season_label": sv["label"],
        "prompt": assemble_prompt(scene_id, season),
        "brightness_target": sv["brightness"],
        "color_overlay": sv["color_overlay"],
        "priority": SCENES[scene_id]["priority"],
        "out_name": f"home_bg_{season}.png",
    }


def main():
    ap = argparse.ArgumentParser(description="场景背景模板：拼装/打印 prompt")
    ap.add_argument("--scene", default=None, help="指定 scene_id（默认全部）")
    ap.add_argument("--season", default=None, help="指定 season（默认全部）")
    ap.add_argument("--json", action="store_true", help="输出 JSON payload 列表")
    args = ap.parse_args()

    scenes = [args.scene] if args.scene else list(SCENES.keys())
    seasons = [args.season] if args.season else list(SEASONS.keys())
    payloads = []
    for sid in scenes:
        if sid not in SCENES:
            print(f"[WARN] 未知 scene_id: {sid}")
            continue
        for s in seasons:
            if s not in SEASONS:
                print(f"[WARN] 未知 season: {s}")
                continue
            if s not in SCENES[sid]["seasons_enabled"]:
                continue
            payloads.append(assemble_payload(sid, s))

    if args.json:
        print(json.dumps(payloads, ensure_ascii=False, indent=2))
    else:
        for p in payloads:
            print(f"\n=== {p['scene_name']} / {p['season_label']} ({p['out_name']}) ===")
            print(p["prompt"])
            print(f"[亮度目标] {p['brightness_target']}  [色调叠层] {p['color_overlay']}")


if __name__ == "__main__":
    main()
