def collect_corpus():
    corpus = set()
    for dp, dn, fn in os.walk(ROOT):
        if ".venv" in dp or "__pycache__" in dp or os.path.basename(dp) == "art":
            dn[:] = [d for d in dn if d not in (".venv", "__pycache__")]
            continue
        for f in fn:
            if not f.endswith(".gd") or f == "game_state.gd":
                continue
            p = os.path.join(dp, f)
            try:
                text = open(p, "rb").read().decode("utf-8")
            except Exception:
                continue
            if "\ufffd" in text:
                continue
            for m in TOKEN_RE.finditer(text):
                corpus.add(m.group())
            for m in STR_RE.finditer(text):
                s = m.group()[1:-1]
                if "\ufffd" not in s:
                    corpus.add(s)
    try:
        import subprocess
        head = subprocess.run(["git", "show", "HEAD:game_state.gd"],
                              capture_output=True).stdout.decode("utf-8", "replace")
        for m in TOKEN_RE.finditer(head):
            if "\ufffd" not in m.group():
                corpus.add(m.group())
        for m in STR_RE.finditer(head):
            s = m.group()[1:-1]
            if "\ufffd" not in s:
                corpus.add(s)
    except Exception:
        pass
    return corpus

