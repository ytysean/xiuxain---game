"""
弟子立绘 · 标准 OpenPose 姿态参考图生成器（男女分版）
=================================================
按 OpenPose COCO 18 关键点配色绘制骨架，供 ControlNet openpose 模块锁定体态。

设计原则（与 master 规范一致）：
  - 底模 = (性格 × 姿态)，同性格角色共用一套体态构图（保证不串型）；
  - 性别差异通过 4 个量化参数叠加，关节点逻辑/文件格式/管线对接 100% 不变：
      ① 肩宽 shoulder   ② 胯宽 hip      ③ 腰节高度 hip_y
      ④ 头身比 head_r / head_y / limb（头占比 + 四肢长度 + 线宽）
  - 男性：倒三角（肩宽胯窄）、腰线下移、四肢偏长偏粗、头占比偏小（7.5–8 头身）；
  - 女性：梨形（肩窄胯宽）、腰线上移、四肢偏短偏细、头占比稍大（7–7.5 头身）。

对齐铁律（用户验收要点一）：
  - 半身姿(halfbody) 的「上身锚点」(鼻0/颈1/右肩2/左肩5/双眼14-15/双耳16-17)
    与同性格 stand 全身姿的上半身**逐点完全重合**，由 UPPER 共享字典保证，
    不各自写死。这样「直接生成半身图」与「全身立绘裁切半身」的头像裁切坐标通用。

力量保留（用户验收要点二）：
  - 战斗姿(battle) 女性版收窄幅度回调（shoulder -24→约-11、hip +22→约+11），
    保留起手张力，避免近战女弟子被画成柔弱摆姿；远程/辅助女弟子仍走柔和默认。

输出文件命名：pose_{性格}_{性别}_{姿态}.png
  （性别=男/女 与 disciple_manifest.csv 的 gender 字段一致；
   性格=chen/gu/wen/bao/jiao/huo2 对应 沉稳/孤傲/温润/暴躁/狡黠/活泼
   —— 与 build_prompt_package.py 的 PERSONALITIES 键严格一致（huo 已被火灵根占用，活泼用 huo2）；
   姿态=stand/battle/halfbody）
  例：pose_chen_男_stand.png  pose_gu_女_halfbody.png

输出目录：弟子立绘/pose/  （1024×1536 竖幅，与立绘同分辨率，姿态映射零偏差）

用法：
  python gen_openpose_refs.py            # 生成全部 36 张（6 性格 × 2 性别 × 3 姿态）
  python gen_openpose_refs.py --out DIR  # 指定输出目录
  python gen_openpose_refs.py --gender 男   # 只生成男版
  python gen_openpose_refs.py --pers huo   # 只生成某性格
"""
